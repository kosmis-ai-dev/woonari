def request():
    return FortuneRequest(
        birth={"year": 1990, "month": 5, "day": 17, "hour": 14, "minute": 30, "gender": "male"},
        target_date=date(2026, 11, 2),
        include_ai=False,
    )


def synthetic_saju(values=("甲子", "丙寅", "甲午", "辛酉")):
    saju = calculate_saju(request().birth)
    master = values[2][0]
    return saju.model_copy(
        update={
            "day_master": master,
            "pillars": {
                k: pillar(v, master) for k, v in zip(("year", "month", "day", "hour"), values)
            },
        }
    )


def test_all_120_original_sipkyuk_cases():
    # Literal source cases, dotong_function.asp:1343-1362, NOT generated by implementation.
    rows = (
        "A1 B2 D3 E4 C5 I5 F6 L6 G7 H8 J9 K0",
        "B1 A2 E3 D4 F5 L5 C6 I6 H7 G8 K9 J0",
        "D1 E2 C3 I3 F4 L4 G5 H6 J7 K8 A9 B0",
        "E1 D2 F3 L3 C4 I4 H5 G6 K7 J8 B9 A0",
        "C1 I1 F2 L2 G3 H4 J5 K6 A7 B8 D9 E0",
        "F1 L1 C2 I2 H3 G4 K5 J6 B7 A8 E9 D0",
        "G1 H2 J3 K4 A5 B6 D7 E8 C9 I9 F0 L0",
        "H1 G2 K3 J4 B5 A6 E7 D8 F9 L9 C0 I0",
        "J1 K2 A3 B4 D5 E6 C7 I7 F8 L8 G9 H0",
        "K1 J2 B3 A4 E5 D6 F7 L7 C8 I8 H9 G0",
    )
    ji_codes = dict(zip("ABCDEFGHIJKL", "寅卯辰巳午未申酉戌亥子丑"))
    gan_codes = dict(zip("1234567890", STEMS))
    count = 0
    for result_code, row in zip("1234567890", rows):
        for key in row.split():
            assert sipkyuk(ji_codes[key[0]], gan_codes[key[1]]) == result_code
            count += 1
    assert count == 120


def test_original_ordered_dangsaju_mapping_and_wraparound():
    assert [dang_code(x) for x in BRANCHES] == list("abcdefghijkl")
    assert dangsaju_code("子", "子") == "a"
    assert dangsaju_code("亥", "子") == "b"  # source case 'la'
    assert dangsaju_code("子", "亥") == "l"  # source case 'al'
    assert dangsaju_code("午", "巳") == "l"  # source case 'gf'
    for first in BRANCHES:
        assert len({dangsaju_code(first, other) for other in BRANCHES}) == 12


def test_lifetime_original_13_rendered_slots_and_selection_keys():
    saju = synthetic_saju()
    decision = decide_life_wealth("lifetime", request(), saju)
    assert decision["unresolved"] == []
    assert decision["facts"]["sipkyuk_code"] == "1"  # 寅月/甲日 比肩格.
    assert decision["facts"]["dangsaju"] == {"year_dang": "a", "mon_dang": "c", "day_dang": "e"}
    slots = {s["id"]: s for s in decision["selectors"]}
    assert len(slots) == 13
    assert slots["lifetime-private-values"]["where"] == {"hname": "甲午"}
    assert slots["lifetime-private-character"]["columns"] == ["desc2"]
    assert slots["lifetime-social-type"]["where"] == {"sipkyuk_code": "1", "unse": "social"}
    assert slots["lifetime-dangsaju-early"]["columns"] == ["desc1"]
    assert slots["lifetime-dangsaju-middle"]["where"] == {"dang_code": "c"}
    assert slots["lifetime-dangsaju-late"]["columns"] == ["desc3"]
    assert slots["lifetime-money-2"]["where"] == {"sipkyuk_code": "1", "unse": "money"}
    assert all(s["where"].get("unse") not in {"jikjang", "job"} for s in slots.values())
    assert "daeun" in {x["component"] for x in decision["facts"]["excluded_non_narrative"]}
    assert len(decision["facts"]["output_bindings"]) == len(slots)


def test_wealth_uses_four_pillar_moneyluck_keys_not_daily_scores():
    saju = synthetic_saju()
    decision = decide_life_wealth("wealth", request(), saju)
    assert decision["unresolved"] == []
    assert len(decision["selectors"]) == 4
    for key, selector in zip(("year", "month", "day", "hour"), decision["selectors"]):
        assert selector["table"] == "Moneyluck"
        assert selector["where"] == {"yukgap": saju.pillars[key].hanja, "daygan": "甲"}
        assert selector["columns"] == ["Money"]
    assert [s["purpose"] for s in decision["selectors"]] == [
        "초년 재물운",
        "장년 재물운",
        "중년 재물운",
        "말년 재물운",
    ]
    assert "score" not in decision["facts"]
    assert decision["facts"]["mybar"] == "1"
    assert decision["facts"]["rendered_inline"]["fivegi"] == "목(木)"
    assert decision["facts"]["rendered_inline"]["notfivegi"] == "토(土)"
    assert decision["facts"]["rendered_inline"]["notcolor"] == "황(黃)"
    assert decision["facts"]["rendered_inline"]["wealth_ki"] == 0


def test_original_weighted_five_ki_uses_60_self_and_half_own_pillar_stage():
    profile = legacy_profile(synthetic_saju())
    # Literal source contributions: 水30+木15, 木80+火45, 火10+木60, 金40+金40.
    assert profile["weighted_five_ki"] == {"목": 155, "화": 55, "토": 0, "금": 80, "수": 30}
    assert profile["graph_divisor"] == 1.55
    assert profile["life_stage_percent"] == {"year": 30, "month": 80, "day": 10, "hour": 40}
    assert profile["gongmang"]["GongL"] == "辰巳"
    assert profile["own_pillar_life_stages"]["month"] == "장생"
    assert TWELVE_PERCENT["태"] == 40
    assert TWELVE_PERCENT["사"] == 10


def test_sinsal_original_call_order_and_hour_uses_day_branch_for_gosin():
    profile = legacy_profile(synthetic_saju())
    assert profile["sinsal"] == {"year": "", "month": "월덕귀인 고신 ", "day": "", "hour": "비인 "}
    changed = legacy_profile(synthetic_saju(("甲子", "丙寅", "甲寅", "辛酉")))
    # Hour branch 酉 does not qualify; source intentionally passes DayJi 寅 here.
    assert "고신 " in changed["sinsal"]["hour"]


def test_original_hyung_two_character_global_replace_is_not_silently_fixed():
    assert "辰辰" not in legacy_hyung("辰辰子丑")
    assert "辰辰(刑) " in legacy_hyung("辰午辰子")
    assert "午午" not in legacy_hyung("午午午午")


def test_original_combination_order():
    profile = legacy_profile(synthetic_saju(("甲申", "己子", "甲辰", "己丑")))
    assert profile["relations"]["GanHap"] == "甲己(土) "
    assert profile["relations"]["SamHap"] == "申子辰(水) "
    assert profile["relations"]["HalfHap"] == "申子(水) 辰子(水) "
    assert profile["relations"]["YukHap"] == "子丑(土) "


