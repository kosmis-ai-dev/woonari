def _selector(identifier, table, where, columns, purpose):
    return {
        "id": identifier,
        "table": table,
        "where": where,
        "columns": columns,
        "purpose": purpose,
    }


def career_dispatch(category: str) -> list[dict]:
    """Port soCode A-E/F and tmpCode='002'; do not invent DLL internals."""
    if category not in {*CAREER_TITLES, "F"}:
        raise DomainError("invalid_career_category", "직업운 career_category는 A~F여야 합니다.")
    groups = list(CAREER_TITLES) if category == "F" else [category]
    return [
        _selector(
            f"career.{group}{i}",
            "NHCP5.NHUnse",
            {"method": "getNHResult", "tmpCode": "002", "soCode": f"{group}{i}"},
            ["unseResult[0]"],
            title,
        )
        for group in groups
        for i, title in enumerate(CAREER_TITLES[group], 1)
    ]


def harmony_content_selectors(my_aisyo: int, other_aisyo: int) -> list[dict]:
    """Exact saju_harmony_1..4 text-query keys once trusted tbAisyo rows exist."""
    for code in (my_aisyo, other_aisyo):
        if isinstance(code, bool) or not isinstance(code, int) or not 1 <= code <= 28:
            raise DomainError("invalid_aisyo_code", "원본 tbAisyo 분류코드(1~28)가 필요합니다.")
    pair_code = AISYO_TABLE[my_aisyo - 1][other_aisyo - 1]
    selectors = []
    for owner, code, title in (
        ("my_mind", my_aisyo, "당신의 마음"),
        ("other_mind", other_aisyo, "상대의 마음"),
    ):
        for part in (1, 2):
            selectors.append(
                _selector(
                    f"compatibility.{owner}.{part}",
                    "tbSajuMaster_mobile1",
                    {"menu": "destiny", "keyno": int(f"{part}{code:02d}")},
                    ["content"],
                    title,
                )
            )
    for part, title in ((3, "두사람의 숙명"), (4, "두사람의 숙명에 대한 조언")):
        selectors.append(
            _selector(
                f"compatibility.harmony.{part}",
                "tbSajuMaster_mobile1",
                {"menu": "harmony", "keyno": int(f"{part}{pair_code:02d}")},
                ["content"],
                title,
            )
        )
    return selectors


def _love(request: FortuneRequest, saju: SajuResult) -> dict:
    # Original CalcMemNo is 9 digits. The first 3 are the day-pillar class.
    day_code = saju.legacy_memno[:3]
    gender_suffix = "m" if request.birth.gender == "male" else "f"
    outputs = (
        ("meeting_time", f"time_{gender_suffix}", "인연을 만날 시기"),
        ("partner_type", "youtype", "내 인연의 성격"),
        ("partner_job", "youjob", "내 인연의 직업"),
        ("meeting_place", "locate", "내 인연과 만날 장소"),
        ("love_method", f"method_{gender_suffix}", "내 사랑 스타일·전략"),
    )
    return {
        "source": LOVE_SOURCE,
        "facts": {
            "dokebi": day_code,
            "gender_field_suffix": gender_suffix,
            "output_fields": [
                {"id": f"love.{key}", "field": column, "topic": title}
                for key, column, title in outputs
            ],
            "source_rule": "CalcMemNo(year,month,day) -> Left(dokebiNo,3); male=m, female=f",
            "narrative_policy": "The five original result fields are AI generation slots. "
            "No daily/target-date score replaces them.",
        },
        "selectors": [
            _selector(f"love.{key}", "tbLoveLuck", {"dokebi": day_code}, [column], title)
            for key, column, title in outputs
        ],
        "unresolved": [],
    }


def _career(request: FortuneRequest) -> dict:
    category = getattr(request, "career_category", None)
    unresolved = [
        "NHCP5.NHUnse.getNHResult('002', soCode): DLL 내부의 직업운 판정·결과 규칙이 "
        "ASP 소스에 없으므로 원본 DLL/구현 명세가 필요합니다."
    ]
    if category is None:
        unresolved.insert(
            0, "accountlist.input10에 해당하는 career_category(A~F) 입력이 필요합니다."
        )
    calls = career_dispatch(category) if category is not None else []
    return {
        "source": CAREER_SOURCE,
        "facts": {
            "tmpCode": "002",
            "soCode": category,
            "categories": {key: list(value) for key, value in CAREER_TITLES.items()},
            "all_categories_code": "F",
            "expected_output_count": 15 if category == "F" else (3 if category else None),
            "original_output_fields": (
                [f"mResult{group}({i})" for group in range(1, 6) for i in range(3)]
                if category == "F"
                else ["mDesc1", "mDesc2", "mDesc3"]
            ),
            "dependency_type": "opaque_business_calculation_and_text",
            "dispatch_only": True,
        },
        "selectors": calls,
        "unresolved": unresolved,
    }


